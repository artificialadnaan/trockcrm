/**
 * REAL-SQL guarantees for the Monday-showcase Service / Other filter (PGlite in-memory Postgres).
 *
 * This suite drives the TOP-LEVEL functions the route handlers call -- getMondayShowcaseData for the
 * payload all 8 variants slice, and getMondayShowcaseEvidence for the drill -- deliberately NOT the SQL
 * builders underneath. The property that matters to a reader of this report is "the card said 6 and the
 * drawer opened 6", and only the top-level pair can assert that. Three things are locked here:
 *
 *   1. RECONCILIATION -- for EVERY filter state (both / service / other), every headline figure equals the
 *      number of records its own evidence query returns. This is the defect class this repo has shipped
 *      repeatedly: a card and its drill-through computed by predicates that drift apart.
 *   2. ADDITIVITY -- service-only + other-only === both-selected, figure by figure. A total partition
 *      cannot lose a row; if this fails, either the predicate is not total or the source is unfilterable.
 *   3. DEFAULT INERTNESS -- the both-buckets payload is deep-equal to the no-filter-at-all payload. A
 *      weekly report must not move a single number because a filter shipped.
 *
 * The one documented exception is Active leads: the `leads` table has no workflow_route, so that figure is
 * NOT additive (it repeats in full under both buckets). That is asserted POSITIVELY below rather than
 * skipped -- a silently-omitted case is how an unfilterable source stops being noticed.
 */

