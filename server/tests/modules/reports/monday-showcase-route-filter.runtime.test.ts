const BOTH: WorkflowRouteBucket[] = ["service", "other"];
const SERVICE: WorkflowRouteBucket[] = ["service"];
const OTHER: WorkflowRouteBucket[] = ["other"];

function showcase(routes?: readonly WorkflowRouteBucket[]): Promise<MondayShowcaseData> {
  return getMondayShowcaseData(tdb, { mode: "to_date", now: NOW, routes });
}

/** The evidence COUNT for one metric/scope under one selection -- what the drawer would show. */
async function evidenceCount(
  metric: Parameters<typeof getMondayShowcaseEvidence>[1]["metric"],
  routes: readonly WorkflowRouteBucket[] | undefined,
  extra: Partial<Parameters<typeof getMondayShowcaseEvidence>[1]> = {}
): Promise<number> {
  const ev = await getMondayShowcaseEvidence(tdb, { metric, mode: "to_date", now: NOW, routes, ...extra });
  return ev.total.count;
}

/**
 * Every headline figure in the payload, reduced to a comparable count. This ONE list is what both the
 * reconciliation and the additivity suites iterate, so a figure can never be filtered-and-tested in one
 * and forgotten in the other. `evidence` describes the drill the number links to.
 */
function figures(data: MondayShowcaseData) {
  const dept = (key: string) => data.departments.find((d) => d.key === key)!;
  return [
    { name: "execHero.won", count: data.execHero.won.count, evidence: { metric: "won" as const } },
    { name: "execHero.sent", count: data.execHero.sent.count, evidence: { metric: "sent" as const } },
    { name: "execHero.estimated", count: data.execHero.estimated.count, evidence: { metric: "estimated" as const } },
    { name: "departments.won", count: dept("won").count ?? -1, evidence: { metric: "won" as const } },
    { name: "departments.sent", count: dept("sent").count ?? -1, evidence: { metric: "sent" as const } },
    { name: "departments.estimating", count: dept("estimating").count ?? -1, evidence: { metric: "estimated" as const } },
    {
      name: "officeProjection.bands(total)",
      count: data.officeProjection.bands.reduce((s, b) => s + b.count, 0),
      evidence: { metric: "projection" as const },
    },
    ...data.officeProjection.bands.map((b) => ({
      name: `officeProjection.band.${b.band}`,
      count: b.count,
      evidence: { metric: "projection" as const, band: b.band },
    })),
    {
      name: "officeProjection.undated(M-N)",
      count: data.officeProjection.coverage.m - data.officeProjection.coverage.n,
      evidence: { metric: "undated" as const },
    },
    {
      name: "officeProjection.blindSpots.stale",
      count: data.officeProjection.blindSpots?.stale.count ?? -1,
      evidence: { metric: "stale" as const },
    },
    {
      name: "officeProjection.blindSpots.noDate",
      count: data.officeProjection.blindSpots?.noDate.count ?? -1,
      evidence: { metric: "no_date" as const },
    },
  ];
}

/** The office lead total, exactly as the B2 footer computes it (Σ every rep bucket incl. Unassigned). */
function leadTotal(data: MondayShowcaseData): number {
  return data.reps.reduce((s, r) => s + r.leadStatus.reduce((t, l) => t + l.count, 0), 0);
}

describe("card count === drilled record count, under EVERY filter state", () => {
  it.each([
    ["both (default)", undefined],
    ["both (explicit)", BOTH],
    ["service only", SERVICE],
    ["other only", OTHER],
  ] as const)("%s", async (_label, routes) => {
    const data = await showcase(routes);
    for (const fig of figures(data)) {
      const drilled = await evidenceCount(fig.evidence.metric, routes, fig.evidence);
      expect(`${fig.name}=${fig.count}`).toBe(`${fig.name}=${drilled}`);
    }
    // Leads too: unfilterable, but the badge and its drill must STILL agree with each other -- that is
    // what makes "unfiltered" honest rather than broken.
    expect(leadTotal(data)).toBe(await evidenceCount("leads", routes));
  });

  it("reconciles per REP as well as office-wide (the B2/B3 row drills)", async () => {
    for (const routes of [BOTH, SERVICE, OTHER]) {
      const data = await showcase(routes);
      expect(data.reps.length).toBeGreaterThan(0);
      for (const rep of data.reps) {
        expect(rep.closed.count).toBe(await evidenceCount("won", routes, { repId: rep.repId }));
        expect(rep.sentThisWeek.count).toBe(await evidenceCount("sent", routes, { repId: rep.repId }));
      }
    }
  });

  it("reconciles $ as well as counts, for the money figures", async () => {
    for (const routes of [BOTH, SERVICE, OTHER]) {
      const data = await showcase(routes);
      const won = await getMondayShowcaseEvidence(tdb, { metric: "won", mode: "to_date", now: NOW, routes });
      expect(won.total.value ?? 0).toBeCloseTo(data.execHero.won.value.amount, 2);
      const sent = await getMondayShowcaseEvidence(tdb, { metric: "sent", mode: "to_date", now: NOW, routes });
      expect(sent.total.value ?? 0).toBeCloseTo(data.execHero.sent.value.amount, 2);
    }
  });
});

describe("additivity: service-only + other-only === both-selected", () => {
  it("holds for every deal-sourced figure", async () => {
    const both = figures(await showcase(BOTH));
    const service = figures(await showcase(SERVICE));
    const other = figures(await showcase(OTHER));
    expect(both).toHaveLength(service.length);
    for (let i = 0; i < both.length; i++) {
      // Name the figure inside the compared strings so a failure says WHICH figure lost rows, not just
      // "expected 5 to be 6" from an anonymous loop.
      expect(`${both[i].name}: service+other=${service[i].count + other[i].count}`).toBe(
        `${both[i].name}: service+other=${both[i].count}`
      );
    }
  });

  it("holds for the Won and Sent $ totals, not just their counts", async () => {
    const both = await showcase(BOTH);
    const service = await showcase(SERVICE);
    const other = await showcase(OTHER);
    expect(service.execHero.won.value.amount + other.execHero.won.value.amount).toBeCloseTo(
      both.execHero.won.value.amount,
      2
    );
    expect(service.execHero.sent.value.amount + other.execHero.sent.value.amount).toBeCloseTo(
      both.execHero.sent.value.amount,
      2
    );
  });

  it("is NON-TRIVIAL: each bucket is a real, strictly smaller slice of a non-zero whole", async () => {
    const both = await showcase(BOTH);
    const service = await showcase(SERVICE);
    const other = await showcase(OTHER);
    // Without these guards every additivity assertion above would pass vacuously on 0 + 0 === 0.
    expect(both.execHero.won.count).toBe(3);
    expect(service.execHero.won.count).toBe(1);
    expect(other.execHero.won.count).toBe(2);
    expect(both.execHero.sent.count).toBe(3);
    expect(service.execHero.sent.count).toBe(1);
    expect(other.execHero.sent.count).toBe(2);
    const bands = (d: MondayShowcaseData) => d.officeProjection.bands.reduce((s, b) => s + b.count, 0);
    expect(bands(both)).toBe(4);
    expect(bands(service)).toBe(2);
    expect(bands(other)).toBe(2);
  });

  it("does NOT hold for Active leads -- the ONE unfilterable figure, asserted rather than skipped", async () => {
    const both = leadTotal(await showcase(BOTH));
    const service = leadTotal(await showcase(SERVICE));
    const other = leadTotal(await showcase(OTHER));
    expect(both).toBe(3); // non-trivial
    // The leads table has no workflow_route: each bucket returns the FULL set, so the buckets sum to
    // double. This is the documented behaviour, not a bug -- and the payload says so out loud below.
    expect(service).toBe(both);
    expect(other).toBe(both);
    expect(service + other).not.toBe(both);
  });
});

describe("a NULL workflow_route counts as Other", () => {
  it("puts the null-route Won deal in Other and never in Service", async () => {
    const service = await getMondayShowcaseEvidence(tdb, { metric: "won", mode: "to_date", now: NOW, routes: SERVICE });
    const other = await getMondayShowcaseEvidence(tdb, { metric: "won", mode: "to_date", now: NOW, routes: OTHER });
    const names = (ev: { records: Array<{ name: string }> }) => ev.records.map((r) => r.name);
    expect(names(other)).toContain("Won null-route unassigned");
    expect(names(service)).not.toContain("Won null-route unassigned");
  });

  it("puts null-route deals in Other for the Sent cohort and the projection snapshot too", async () => {
    const sentOther = await getMondayShowcaseEvidence(tdb, { metric: "sent", mode: "to_date", now: NOW, routes: OTHER });
    expect(sentOther.records.map((r) => r.name)).toContain("Sent null-route A");
    const projOther = await getMondayShowcaseEvidence(tdb, { metric: "projection", mode: "to_date", now: NOW, routes: OTHER });
    expect(projOther.records.map((r) => r.name)).toContain("Proj null-route 0_30");
  });
});

describe("the default state is inert", () => {
  it("both-buckets returns a payload deep-equal to passing no filter at all", async () => {
    expect(await showcase(BOTH)).toEqual(await showcase(undefined));
  });

  it("bucket ORDER does not change the payload", async () => {
    expect(await showcase(["other", "service"])).toEqual(await showcase(BOTH));
  });

  it("describes itself as inactive, with nothing disclaimed", async () => {
    const data = await showcase(undefined);
    expect(data.routeFilter).toEqual({ selected: ["service", "other"], active: false, unfilterable: [] });
    // No route caveat is appended to the source notes when nothing is narrowed.
    expect(data.notes.some((note) => note.includes("Filtered to"))).toBe(false);
  });
});

describe("the payload names what the filter could not reach", () => {
  it("flags the unfilterable figures when (and only when) the selection narrows", async () => {
    const data = await showcase(SERVICE);
    expect(data.routeFilter.active).toBe(true);
    expect(data.routeFilter.selected).toEqual(["service"]);
    expect(data.routeFilter.unfilterable.join(" ")).toMatch(/Active leads/);
    expect(data.routeFilter.unfilterable.join(" ")).toMatch(/Collected/);
    expect(data.notes.some((note) => note.includes("Filtered to Service only"))).toBe(true);
  });

  it("keeps the routeFilter field and the source notes describing the SAME state", async () => {
    // The notes are the mechanism that discloses "Active leads are not route-filtered". If the payload
    // could declare one filter state while its own notes described another, that disclosure would be
    // unreliable exactly when it matters. Both are derived from ONE resolved descriptor; this pins that.
    for (const routes of [undefined, BOTH, SERVICE, OTHER]) {
      const data = await showcase(routes);
      const notesClaimNarrowing = data.notes.some((note) => note.includes("Filtered to"));
      expect(`routes=${routes ?? "absent"} notesNarrow=${notesClaimNarrowing}`).toBe(
        `routes=${routes ?? "absent"} notesNarrow=${data.routeFilter.active}`
      );
      if (data.routeFilter.active) {
        // The note names the SAME bucket the field carries, and repeats the same unfilterable list.
        // Matched on the bucket WORD, not the full label ("Other (non-service)"), so the copy can be
        // reworded without this becoming a wording test -- what is pinned is that they agree.
        const bucketWord = data.routeFilter.selected[0] === "service" ? "Service" : "Other";
        expect(data.notes.some((note) => note.includes(`Filtered to ${bucketWord}`))).toBe(true);
        const otherWord = bucketWord === "Service" ? "Other" : "Service";
        expect(data.notes.some((note) => note.includes(`Filtered to ${otherWord}`))).toBe(false);
        for (const figure of data.routeFilter.unfilterable) {
          expect(data.notes.some((note) => note.includes(figure))).toBe(true);
        }
      }
    }
  });

  it("marks the leads DRILL as not-applied while every deal drill is applied", async () => {
    const leads = await getMondayShowcaseEvidence(tdb, { metric: "leads", mode: "to_date", now: NOW, routes: SERVICE });
    expect(leads.routeFilter).toEqual({ selected: ["service"], active: true, applied: false });
    for (const metric of ["won", "sent", "estimated", "projection", "undated", "stale", "no_date"] as const) {
      const ev = await getMondayShowcaseEvidence(tdb, { metric, mode: "to_date", now: NOW, routes: SERVICE });
      expect(`${metric}.applied=${ev.routeFilter.applied}`).toBe(`${metric}.applied=true`);
    }
  });

  it("reports applied=false for every metric when the selection does not narrow", async () => {
    const ev = await getMondayShowcaseEvidence(tdb, { metric: "won", mode: "to_date", now: NOW, routes: BOTH });
    expect(ev.routeFilter).toEqual({ selected: ["service", "other"], active: false, applied: false });
  });
});

describe("an empty selection has no payload", () => {
  it("throws rather than returning a full or zeroed report", async () => {
    await expect(showcase([])).rejects.toThrow(/at least one/i);
    await expect(
      getMondayShowcaseEvidence(tdb, { metric: "won", mode: "to_date", now: NOW, routes: [] })
    ).rejects.toThrow(/at least one/i);
  });
});
