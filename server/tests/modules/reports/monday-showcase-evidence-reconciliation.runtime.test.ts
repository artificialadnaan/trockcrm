describe("Won evidence reconciles to the protected getWonCloseSummary", () => {
  it("office Won: evidence rows === count, sum(value) === $", async () => {
    const agg = await getWonCloseSummary(tdb, { from: FROM, to: TO });
    const rows = await execRows(buildWonEvidenceSql(FROM, TO));
    expect(agg.count).toBe(3); // meaningful, non-trivial
    expect(rows.length).toBe(agg.count);
    expect(sumVal(rows)).toBeCloseTo(agg.totalValue, 2);
    const nums = rows.map((r) => r.deal_number);
    expect(nums).not.toContain("W-4"); // on-hold
    expect(nums).not.toContain("W-5"); // test
    expect(nums).not.toContain("W-6"); // out of window
    // the new project_number column surfaces in the row payload: the canonical DFW number rides alongside
    // the raw HubSpot deal_number, so the client resolver can show the DFW number and hide the HS id
    const w1 = rows.find((r) => r.project_number === "DFW-1-09026-af");
    expect(w1).toBeTruthy();
    expect(w1?.deal_number).toBe("HS-318651319000");
  });

  it("per-rep Won: each rep's evidence === getCanonicalRepWonSummary row, and per-rep sums to office", async () => {
    const repRows = await getCanonicalRepWonSummary(tdb, { from: FROM, to: TO });
    expect(repRows.length).toBeGreaterThan(0);
    for (const rr of repRows) {
      const rows = await execRows(buildWonEvidenceSql(FROM, TO, rr.repId));
      expect(rows.length).toBe(rr.winsCount);
      expect(sumVal(rows)).toBeCloseTo(rr.closedValue, 2);
    }
    const office = await execRows(buildWonEvidenceSql(FROM, TO));
    const repSum = (await Promise.all(repRows.map((rr) => execRows(buildWonEvidenceSql(FROM, TO, rr.repId)))))
      .reduce((s, rows) => s + rows.length, 0);
    expect(repSum).toBe(office.length);
  });
});

async function aggregateCohort(slugs: readonly string[]): Promise<{ count: number; value: number; byRep: Map<string | null, { count: number; value: number }> }> {
  const rows = await execRows(buildStageEntryCohortSql(slugs, FROM, TO));
  const byRep = new Map<string | null, { count: number; value: number }>();
  let count = 0;
  let value = 0;
  for (const r of rows) {
    const repId = (r.rep_id as string | null) ?? null;
    const c = n(r.cnt);
    const v = n(r.val);
    byRep.set(repId, { count: c, value: v });
    count += c;
    value += v;
  }
  return { count, value, byRep };
}

