function execRows(q: SQL): Promise<Array<Record<string, unknown>>> {
  return tdb.execute(q).then((r: unknown) => {
    if (Array.isArray(r)) return r as Array<Record<string, unknown>>;
    return ((r as { rows?: Array<Record<string, unknown>> })?.rows ?? []) as Array<Record<string, unknown>>;
  });
}
const n = (v: unknown) => Number(v ?? 0);
const sumVal = (rows: Array<Record<string, unknown>>) => rows.reduce((s, r) => s + n(r.value), 0);

